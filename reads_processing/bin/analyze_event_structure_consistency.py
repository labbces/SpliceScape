#!/usr/bin/env python3
"""Read-only cross-sample event-structure audit for SpliceScape v2.4.

Input: event_definitions.tsv and order_dependent_psi.tsv generated by
analyze_event_recurrence.py. Does not open/write biological databases or TSVs.

Only rows with grouping_status='native' are treated as reconstructed event
structures. SGSeq rows without an event identifier were previously marked
'ungrouped_row': they cannot establish multi-junction event membership.

An exact match here means identical normalized junction-coordinate sets and
source event type WITHIN ONE TOOL. Role comparisons use the precomputed
role_signature, not independent validation of inclusion/exclusion semantics.
"""
import argparse
from collections import Counter, defaultdict
import csv
import json
from pathlib import Path
import sys


def get_rows(path, required):
    with path.open('r', encoding='utf-8-sig', newline='') as fh:
        r = csv.DictReader(fh, delimiter='\t')
        if not r.fieldnames or not set(required).issubset(r.fieldnames):
            raise ValueError(f'{path}: missing required columns: {sorted(set(required)-set(r.fieldnames or []))}')
        yield from r


def parse_coord(text):
    """Return chrom,start,end,strand, or fail without guessing coordinates."""
    chrom, interval, strand = text.rsplit(':', 2)
    start, end = interval.split('-', 1)
    a, b = int(start), int(end)
    if not chrom or strand not in ('+', '-') or a >= b:
        raise ValueError(f'Invalid junction coordinate: {text!r}')
    return chrom, a, b, strand


def parse_junction_id(jid, reference):
    """Original parser's reference_chr:start-end_strand_eventtype identifier."""
    prefix = reference + '_'
    if not jid.startswith(prefix):
        return None
    try:
        loc, strand, event_type = jid[len(prefix):].rsplit('_', 2)
        chrom, interval = loc.rsplit(':', 1)
        a, b = interval.split('-', 1)
        if int(a) >= int(b) or strand not in ('+', '-'):
            return None
        return (chrom, int(a), int(b), strand), event_type
    except (ValueError, TypeError):
        return None


def analyze(event_file, psi_file, reference, overlap_limit=1000, preview_limit=100):
    # Keys are tool + source event type + sorted *entire* junction set.
    # The signature hash is retained as a convenient join key, but not trusted
    # as the only evidence for structural identity.
    events = {}
    excluded = Counter()
    sig_to_key = {}
    examples_conflict = []
    for row in get_rows(event_file, ('tool', 'sample', 'event_type', 'grouping_status',
                                     'topology_signature', 'role_signature', 'junction_coordinates')):
        tool, sample, etype = row['tool'], row['sample'], row['event_type']
        if row['grouping_status'] != 'native':
            excluded[(tool, row['grouping_status'])] += 1
            continue
        try:
            coords = frozenset(parse_coord(c) for c in row['junction_coordinates'].split(';') if c)
        except ValueError:
            excluded[(tool, 'invalid_coordinate_string')] += 1
            continue
        if not coords:
            excluded[(tool, 'empty_junction_set')] += 1
            continue
        key = (tool, etype, coords)
        sig = row['topology_signature']
        prior = sig_to_key.setdefault((tool, sig), key)
        if prior != key:
            raise ValueError(f'Hash collision/inconsistent topology definition for {tool} {sig}')
        ev = events.get(key)
        if ev is None:
            ev = {'tool':tool, 'event_type':etype, 'coords':coords,
                  'signature':sig, 'samples':set(), 'roles':defaultdict(set),
                  'native_ids':set(), 'occurrences':0}
            events[key] = ev
        ev['samples'].add(sample)
        ev['roles'][sample].add(row['role_signature'])
        ev['occurrences'] += 1
        if row.get('native_event_id'):
            ev['native_ids'].add(row['native_event_id'])

    by_tool = defaultdict(list)
    junction_to_events = defaultdict(set)
    for key, ev in events.items():
        by_tool[ev['tool']].append(key)
        for coord in ev['coords']:
            junction_to_events[(ev['tool'], ev['event_type'], coord)].add(key)

    summary = {'reference': reference,
               'definitions_file':str(event_file),
               'psi_file':str(psi_file),
               'excluded_event_occurrences':{f'{k[0]}:{k[1]}':v for k,v in sorted(excluded.items())},
               'note':'Only native-grouped events; same topology means same complete coordinate set within tool and event type. Role hash checks cannot validate biological equivalence of denominators.',
               'tools':{}}
    topology_rows = []
    role_conflicts = []
    for tool, keys in sorted(by_tool.items()):
        tool_events = [events[k] for k in keys]
        repeated = [e for e in tool_events if len(e['samples']) > 1]
        conflicting = [e for e in repeated if len(set().union(*e['roles'].values())) > 1]
        within_sample_conflicts = [e for e in tool_events if any(len(r) > 1 for r in e['roles'].values())]
        sample_role_count = Counter()
        for e in tool_events:
            roles = set().union(*e['roles'].values())
            kind = 'role_conflict' if len(roles)>1 else 'role_consistent'
            if len(e['samples']) > 1:
                sample_role_count[kind] += 1
            topology_rows.append([tool,e['event_type'],e['signature'],len(e['samples']),
                                  ','.join(sorted(e['samples'])),len(e['coords']),
                                  len(roles),kind if len(e['samples'])>1 else 'singleton',
                                  ';'.join(f'{c[0]}:{c[1]}-{c[2]}:{c[3]}' for c in sorted(e['coords']))])
            if len(roles)>1:
                role_conflicts.append([tool,e['event_type'],e['signature'],len(e['samples']),
                                       ';'.join(f'{s}:{",".join(sorted(r))}' for s,r in sorted(e['roles'].items()))])
        summary['tools'][tool] = {
            'canonical_structures_with_native_grouping':len(tool_events),
            'structures_in_multiple_samples':len(repeated),
            'shared_structures_with_identical_role_hashes':sample_role_count['role_consistent'],
            'shared_structures_with_conflicting_role_hashes':sample_role_count['role_conflict'],
            'structures_with_multiple_roles_within_a_sample':len(within_sample_conflicts),
            'single_sample_structures':len(tool_events)-len(repeated),
        }

    # Efficient candidate enumeration: inverted index by junction; compare only
    # pairs sharing at least one coordinate AND the same event type and tool.
    # No all-versus-all topology comparison. Extremely high-degree junctions can
    # cause quadratic growth; skip explicitly and report the excluded loci.
    pairs = {}
    skipped = []
    for (tool,etype,coord), keys in junction_to_events.items():
        if len(keys)>overlap_limit:
            skipped.append((tool,etype,coord,len(keys)))
            continue
        distinct = sorted((events[k]['signature'] for k in keys))
        for i, left in enumerate(distinct):
            for right in distinct[i+1:]:
                key = (tool,etype,left,right)
                pairs[key] = pairs.get(key,0) + 1
    sig_index = {(e['tool'],e['event_type'],e['signature']):e for e in events.values()}
    overlap_rows = []
    per_tool_overlaps = Counter()
    partial_signatures = defaultdict(set)
    for (tool,etype,left,right),intersection in sorted(pairs.items()):
        a=sig_index[(tool,etype,left)];b=sig_index[(tool,etype,right)]
        if len(a['coords'])==len(b['coords'])==intersection:
            raise RuntimeError('Distinct signatures have identical full coordinate sets')
        union=len(a['coords'])+len(b['coords'])-intersection
        jaccard=intersection/union
        shared=sorted(a['samples'] & b['samples'])
        per_tool_overlaps[(tool,'partial_pairs')]+=1
        if shared:per_tool_overlaps[(tool,'pairs_copresent_in_samples')]+=1
        partial_signatures[tool].update((left,right))
        overlap_rows.append([tool,etype,left,right,intersection,len(a['coords']),
                             len(b['coords']),round(jaccard,8),len(shared),','.join(shared)])
    for tool in by_tool:
        summary['tools'][tool].update({
            'partially_overlapping_structure_pairs':per_tool_overlaps[(tool,'partial_pairs')],
            'partial_overlap_pairs_detected_in_same_sample':per_tool_overlaps[(tool,'pairs_copresent_in_samples')],
            'structures_with_partial_overlap':len(partial_signatures[tool]),
        })
    summary['partial_overlap_index']={
        'max_topologies_per_junction':overlap_limit,
        'junctions_excluded_due_to_high_degree':len(skipped),
        'overlap_pairs_are_exhaustive':not bool(skipped),
    }

    # Compare PSI discrepancies to structural annotations, NOT causes.
    psi_rows=[]
    psi_summary=defaultdict(Counter)
    for row in get_rows(psi_file,('tool','sample','junctionID','forward_psi','reverse_psi')):
        tool,sample,jid=row['tool'],row['sample'],row['junctionID']
        parsed=parse_junction_id(jid,reference)
        if parsed is None:
            psi_summary[tool]['unparsed_junction_id']+=1
            continue
        coord, etype=parsed
        associated=[events[k] for k in junction_to_events.get((tool,etype,coord),())]
        sample_associated=[e for e in associated if sample in e['samples']]
        shared_role_conflicts=[e for e in associated if len(e['samples'])>1 and
                               len(set().union(*e['roles'].values()))>1]
        same_sample_multiple=len(sample_associated)>1
        global_multiple=len(associated)>1
        implicated_conflict=bool(shared_role_conflicts)
        psi_summary[tool]['discrepancies']+=1
        if not associated:psi_summary[tool]['not_linked_to_reconstructed_event']+=1
        if same_sample_multiple:psi_summary[tool]['multiple_topologies_in_sample']+=1
        if global_multiple:psi_summary[tool]['multiple_topologies_across_samples']+=1
        if implicated_conflict:psi_summary[tool]['associated_with_role_conflict']+=1
        if any(e['signature'] in partial_signatures[tool] for e in associated):
            psi_summary[tool]['associated_with_partial_overlap']+=1
        psi_rows.append([tool,sample,jid,row['forward_psi'],row['reverse_psi'],
                         row.get('absolute_difference',''),len(associated),len(sample_associated),
                         int(same_sample_multiple),int(implicated_conflict),
                         int(any(e['signature'] in partial_signatures[tool] for e in associated)),
                         ','.join(sorted(e['signature'] for e in sample_associated))])
    summary['psi_discrepancies']={k:dict(v) for k,v in sorted(psi_summary.items())}
    return summary,topology_rows,role_conflicts,overlap_rows,psi_rows,skipped


def output_tsv(path,headers,rows):
    with path.open('w',newline='',encoding='utf-8') as h:
        writer=csv.writer(h,delimiter='\t');writer.writerow(headers);writer.writerows(rows)


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--events',required=True,type=Path,help='event_definitions.tsv')
    ap.add_argument('--psi',required=True,type=Path,help='order_dependent_psi.tsv')
    ap.add_argument('--genome-version',required=True)
    ap.add_argument('--output',required=True,type=Path,help='New, nonexistent results directory')
    ap.add_argument('--max-topologies-per-junction',type=int,default=1000,
                    help='Safety cap for enumerating overlapping event pairs; excluded loci are reported')
    args=ap.parse_args()
    if args.output.exists():ap.error('Output directory already exists; choose a fresh path')
    if not args.events.is_file() or not args.psi.is_file():ap.error('Missing input TSV')
    if args.max_topologies_per_junction < 2:ap.error('Overlap cap must be >=2')
    data=analyze(args.events,args.psi,args.genome_version,args.max_topologies_per_junction)
    summary,topologies,conflicts,overlaps,psi,skipped=data
    args.output.mkdir(parents=True)
    (args.output/'structure_summary.json').write_text(json.dumps(summary,indent=2)+'\n',encoding='utf-8')
    output_tsv(args.output/'topology_role_consistency.tsv',
               ['tool','event_type','topology_signature','sample_count','samples','junction_count',
                'role_hash_count','role_status','junction_coordinates'],topologies)
    output_tsv(args.output/'role_conflicts.tsv',
               ['tool','event_type','topology_signature','sample_count','sample_role_hashes'],conflicts)
    output_tsv(args.output/'partial_overlap_pairs.tsv',
               ['tool','event_type','topology_A','topology_B','shared_junction_count',
                'junctions_A','junctions_B','jaccard','shared_sample_count','shared_samples'],overlaps)
    output_tsv(args.output/'psi_structural_context.tsv',
               ['tool','sample','junctionID','forward_psi','reverse_psi','absolute_difference',
                'event_structures_total','event_structures_in_sample','multiple_in_sample',
                'linked_to_role_conflict','linked_to_partial_overlap','sample_topology_signatures'],psi)
    output_tsv(args.output/'high_degree_junctions_excluded.tsv',
               ['tool','event_type','chrom','start','end','strand','number_of_topologies'],
               ([tool,etype,*coord,n] for tool,etype,coord,n in skipped))
    print(json.dumps(summary,indent=2))
    print('Outputs:',args.output)

if __name__=='__main__':
    try:main()
    except (ValueError,RuntimeError) as exc:
        sys.exit('ERROR: '+str(exc))